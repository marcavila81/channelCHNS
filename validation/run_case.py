#!/usr/bin/env python3
"""Run a validation/sanity case end to end.

Steps: write case.in from the case JSON, (optionally) run the binary in
--workdir, then run analysis.py on the output directory and report PASS/FAIL.

Examples:
    python run_case.py case1_static_cap_th50_Bo0.json --workdir /scratch/run1
    python run_case.py sanity_th50_Bo0_coarse.json --workdir /scratch/sanity \
        --build-flags "-DNY=65 -DNX=64 -DNZ=33 -DCn=0.05 -Ddt=1e-4"
    python run_case.py case1_static_cap_th50_Bo0.json --dry-run   # only write case.in
"""
import argparse
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("case", help="case JSON file")
    ap.add_argument("--workdir", default=".", help="directory where the binary runs")
    ap.add_argument("--binary", default=None, help="path to wnCH_NS (default: JSON 'binary', relative to the case file)")
    ap.add_argument("--dry-run", action="store_true", help="only write case.in into workdir")
    ap.add_argument("--no-run", action="store_true", help="skip running the binary")
    ap.add_argument("--no-analyze", action="store_true", help="skip the analysis step")
    ap.add_argument("--build-flags", default=None,
                    help="if given, rebuild the code first: make -C <codedir> clean && make FLAGS=...")
    args = ap.parse_args()

    case_path = Path(args.case).resolve()
    case = json.load(open(case_path))
    workdir = Path(args.workdir).resolve()
    workdir.mkdir(parents=True, exist_ok=True)

    # 1. write case.in from the JSON runtime_input
    ri = case["runtime_input"]
    lines = [f"# {case['name']}", f"# generated by run_case.py from {case_path.name}"]
    for k, v in ri.items():
        lines.append(f"{k} {v}")
    (workdir / "case.in").write_text("\n".join(lines) + "\n")
    print(f"wrote {workdir/'case.in'}")
    outdir = str(ri.get("outdir", "output"))
    data_dir = workdir / outdir

    # 2. optional rebuild with flags
    if args.build_flags is not None:
        binary = Path(args.binary) if args.binary else case_path.parent / case["binary"]
        codedir = binary.resolve().parent
        flags = args.build_flags if args.build_flags != "" else case.get("build_flags", "")
        env = os.environ.copy()
        if shutil.which("nvcc", path=env.get("PATH")) is None:
            env["PATH"] = env.get("PATH", "") + ":/usr/local/cuda/bin:/usr/local/cuda-13/bin:/usr/local/cuda-13.3/bin"
        subprocess.run(["make", "-C", str(codedir), "clean"], check=True, env=env)
        subprocess.run(["make", "-C", str(codedir), "-j4", f"FLAGS={flags}"], check=True, env=env)

    # 3. run the binary
    if args.dry_run:
        print("dry-run: stopping after case.in"); return
    if not args.no_run:
        binary = Path(args.binary) if args.binary else case_path.parent / case["binary"]
        r = subprocess.run([str(binary), "case.in"], cwd=workdir)
        if r.returncode != 0:
            print(f"RUN FAILED (exit {r.returncode})"); sys.exit(r.returncode)
        # hard check: all files the case expects were produced
        missing = [f for f in case.get("hard_checks", {}).get("files", [])
                   if not (data_dir / f).exists()]
        if missing:
            print(f"HARD CHECK FAIL after run: missing {missing} in {data_dir}")
            sys.exit(2)
        print(f"hard check OK: all files present in {data_dir}")

    # 4. analyze
    if not args.no_analyze:
        r = subprocess.run([sys.executable, str(HERE / "analysis.py"),
                            "--case", str(case_path), "--data", str(data_dir)])
        sys.exit(r.returncode)


if __name__ == "__main__":
    main()
